"""
ccs_log_to_json.py
------------------
Parses a Code Composer Studio (CCS) build log generated by the TI cl2000
compiler and produces a compile_commands.json file suitable for use with
Polyspace (or any Clang-based static analysis tool).

This script is intended to be called from a CCS post-build step so that
CCS built-in variables resolve the paths automatically — no hardcoding needed.

CCS Post-Build Command
----------------------
    python "${ProjDirPath}/Debug/ccs_log_to_json.py" "${WorkspaceDirPath}" "${ProjDirPath}" "${ProjName}"

Arguments (supplied automatically by CCS)
-----------------------------------------
    argv[1]  ${WorkspaceDirPath}  e.g. D:/Worlspace/V12
    argv[2]  ${ProjDirPath}       e.g. D:/git repositories/.../Source Code
    argv[3]  ${ProjName}          e.g. EBUS_TMS

Derived paths
-------------
    Build log   : <WorkspaceDirPath>/.metadata/.plugins/org.eclipse.cdt.ui/<ProjName>.build.log
    Output JSON : <ProjDirPath>/Debug/compile_commands.json
"""

import re
import json
import os
import sys

# ---------------------------------------------------------------------------
# Resolve paths from CCS-supplied arguments
# ---------------------------------------------------------------------------

if len(sys.argv) != 4:
    print("[ERROR] Expected 3 arguments from CCS post-build step:")
    print("        1) ${WorkspaceDirPath}")
    print("        2) ${ProjDirPath}")
    print("        3) ${ProjName}")
    print("")
    print("  Post-build command should be:")
    print('  python "${ProjDirPath}/Debug/ccs_log_to_json.py" "${WorkspaceDirPath}" "${ProjDirPath}" "${ProjName}"')
    raise SystemExit(1)

WORKSPACE_DIR    = sys.argv[1]
PROJECT_DIR      = sys.argv[2]
PROJECT_NAME     = sys.argv[3]

# CCS always writes the build log here:
BUILD_LOG_PATH   = os.path.join(
    WORKSPACE_DIR,
    ".metadata", ".plugins", "org.eclipse.cdt.ui",
    PROJECT_NAME + ".build.log"
)

# Output JSON goes into the Debug folder of the project:
OUTPUT_JSON_PATH = os.path.join(PROJECT_DIR, "Debug", "compile_commands.json")

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# TI flag  ->  Polyspace / GCC-style equivalent  (empty string = drop the flag)
FLAG_MAP = {
    "--c89": "-std=c89",
    "--c99": "-std=c99",
    "--c11": "-std=c11",
    "--c17": "-std=c17",
    "-g":    "-g",
    "--fp_mode=strict":  "",
    "--fp_mode=relaxed": "",
}

# TI-specific flag prefixes that Polyspace does not understand -> drop them
DROP_FLAG_PREFIXES = (
    "--preproc_dependency",
    "--preproc_with_compile",
    "--obj_directory",
    "--abi",
    "--advice",
    "--diag_warning",
    "--diag_wrap",
    "--display_error_number",
    "-v28",
    "-ml",
    "-mt",
    "--cla_support",
    "--float_support",
    "--tmu_support",
    "--vcu_support",
)


def normalize_path(p):
    """Strip surrounding quotes and normalise slashes."""
    p = p.strip().strip('"').strip("'")
    return os.path.normpath(p)


# ---------------------------------------------------------------------------
# Main parser
# ---------------------------------------------------------------------------

def parse_build_log(log_path):
    """
    Read a CCS build log and return a list of compile-command entries.

    Each entry follows the compile_commands.json schema:
        {
            "file":      "<absolute source file path>",
            "directory": "<build directory>",
            "arguments": ["compiler", "-Ifoo", "-DBAR", ..., "file"]
        }
    """
    with open(log_path, "r", encoding="utf-8", errors="replace") as fh:
        lines = fh.readlines()

    entries = []

    compiler_re      = re.compile(r'"(?P<compiler>[^"]+[/\\]cl2000)"(?P<args>.*)')
    include_eq_re    = re.compile(r'--include_path="([^"]+)"')
    include_space_re = re.compile(r'--include_path\s+"([^"]+)"')
    define_re        = re.compile(r'--define=([^\s]+)')
    source_re        = re.compile(r'"(\.\.[^"]+\.[cCsS])"')

    # Build directory: the Debug folder where compile_commands.json is written
    build_dir = os.path.dirname(os.path.abspath(OUTPUT_JSON_PATH))

    for line in lines:
        m = compiler_re.search(line)
        if not m:
            continue

        compiler_path = normalize_path(m.group("compiler"))
        args_str      = m.group("args")

        # --- source file (last "../some/file.c" on the line) ---
        src_matches = source_re.findall(args_str)
        if not src_matches:
            continue
        raw_source = src_matches[-1]
        source_abs = os.path.normpath(
            os.path.join(build_dir, raw_source.replace("/", os.sep))
        )

        # --- include paths ---
        includes = []
        seen = set()
        for path in include_eq_re.findall(args_str) + include_space_re.findall(args_str):
            norm = normalize_path(path)
            if norm not in seen:
                seen.add(norm)
                includes.append("-I" + norm)

        # --- defines ---
        defines = ["-D" + d for d in define_re.findall(args_str)]

        # --- standard flags (-g, C standard) ---
        std_flags = []
        for token in ("-g", "--c89", "--c99", "--c11", "--c17"):
            if token in args_str:
                mapped = FLAG_MAP.get(token, "")
                if mapped and mapped not in std_flags:
                    std_flags.append(mapped)

        arguments = [compiler_path] + std_flags + includes + defines + [source_abs]

        entries.append({
            "file":      source_abs,
            "directory": build_dir,
            "arguments": arguments,
        })

    return entries


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main():
    log_path = BUILD_LOG_PATH
    out_path = OUTPUT_JSON_PATH

    print("[INFO] Workspace:  " + WORKSPACE_DIR)
    print("[INFO] Project:    " + PROJECT_NAME)
    print("[INFO] Build log:  " + log_path)
    print("[INFO] Output:     " + out_path)

    # --- validate log path ---
    if not os.path.isfile(log_path):
        print("[ERROR] Build log not found:")
        print("        " + log_path)
        raise SystemExit(1)

    # --- validate output path (must be a file path, not a directory) ---
    if os.path.isdir(out_path):
        print("[ERROR] OUTPUT_JSON_PATH points to a directory, not a file:")
        print("        " + out_path)
        raise SystemExit(1)

    # --- ensure output directory exists ---
    out_dir = os.path.dirname(out_path)
    if out_dir and not os.path.isdir(out_dir):
        print("[ERROR] Output directory does not exist:")
        print("        " + out_dir)
        raise SystemExit(1)

    entries = parse_build_log(log_path)

    if not entries:
        print("[WARNING] No compiler invocations found. Check the log format.")
        raise SystemExit(1)

    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(entries, fh, indent=2)

    print("[INFO] " + str(len(entries)) + " entries written -> " + out_path)


if __name__ == "__main__":
    main()